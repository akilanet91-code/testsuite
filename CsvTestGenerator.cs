using System.Text.RegularExpressions;
using ClosedXML.Excel;

namespace TestFlow;

/// <summary>Reads a CSV (or any delimited text) file and generates, from its content:
/// 1) a spec workbook (sheet "Mapping": TargetColumn, SourceColumn, DataType, Required, Pattern, ExpectedValue, Notes)
/// 2) a test case workbook (sheet "TestCases") with ExcelVerify cases that point at the CSV and that spec.
/// Use a CSV that is known to be GOOD: the rules are learned from it, so errors in the sample become rules.</summary>
public static class CsvTestGenerator
{
    static readonly Regex EmailRx = new(@"^\S+@\S+$", RegexOptions.Compiled);

    public record ColumnProfile(string Name, string DataType, bool Required, string Pattern, string ExpectedValue, string Notes);
    public record Result(string SpecPath, string CasesPath, int Columns, int Rows, List<ColumnProfile> Profile, List<string> Warnings);

    /// <summary>Reads the CSV and infers one rule per column. Delimiter blank = auto-detect.</summary>
    public static (List<ColumnProfile> profile, int rows, List<string> warnings) Analyse(string csvPath, string delimiter = "")
    {
        var warnings = new List<string>();
        var rows = GeneratedReader.Read(csvPath, new List<Dictionary<string, string>>(), delimiter, true, w => warnings.Add(w));
        if (rows.Count == 0) throw new InvalidDataException("The CSV has no data rows (a header line and at least one data line are needed).");

        var profile = new List<ColumnProfile>();
        foreach (var col in rows[0].Keys)
        {
            if (string.IsNullOrWhiteSpace(col)) { warnings.Add("A column with an empty header name was skipped."); continue; }
            var values = rows.Select(r => r.GetValueOrDefault(col, "")).ToList();
            var filled = values.Where(v => v.Length > 0).ToList();
            bool required = filled.Count == values.Count;

            string type = "text", pattern = "", expected = "";
            if (filled.Count > 0)
            {
                if (filled.All(v => bool.TryParse(v, out _))) type = "bool";
                else if (filled.All(v => int.TryParse(v, out _))) type = "int";
                else if (filled.All(v => decimal.TryParse(v, out _))) type = "decimal";
                else if (filled.All(v => (v.Contains('-') || v.Contains('/')) && DateTime.TryParse(v, out _))) type = "date";
                else if (filled.All(v => v.Contains('@') && EmailRx.IsMatch(v))) pattern = EmailRx.ToString();

                if (type == "text" && pattern == "" && rows.Count >= 2 && filled.Distinct(StringComparer.OrdinalIgnoreCase).Count() == 1 && required)
                    expected = filled[0];
            }

            var notes = $"Learned from {rows.Count} row(s)" + (filled.Count == 0 ? "; column is empty in the sample" : "");
            profile.Add(new ColumnProfile(col.Trim(), type, required, pattern, expected, notes));
        }
        return (profile, rows.Count, warnings);
    }

    /// <summary>Analyses the CSV, then writes the spec workbook and the test case workbook.</summary>
    public static Result Generate(string csvPath, string casesPath, string delimiter = "")
    {
        var (profile, rowCount, warnings) = Analyse(csvPath, delimiter);
        var specPath = Path.Combine(Path.GetDirectoryName(Path.GetFullPath(casesPath)) ?? "",
            Path.GetFileNameWithoutExtension(casesPath) + "_Spec.xlsx");
        SaveSpec(specPath, profile);
        SaveCases(casesPath, specPath, csvPath, delimiter);
        return new Result(specPath, casesPath, profile.Count, rowCount, profile, warnings);
    }

    static void SaveSpec(string path, List<ColumnProfile> profile)
    {
        using var wb = new XLWorkbook();
        var ws = wb.AddWorksheet("Mapping");
        string[] h = { "TargetColumn", "SourceColumn", "DataType", "Required", "Pattern", "ExpectedValue", "Notes" };
        for (int i = 0; i < h.Length; i++) ws.Cell(1, i + 1).Value = h[i];
        ws.Row(1).Style.Font.Bold = true;
        int r = 2;
        foreach (var p in profile)
        {
            ws.Cell(r, 1).Value = p.Name; ws.Cell(r, 2).Value = p.Name; ws.Cell(r, 3).Value = p.DataType;
            ws.Cell(r, 4).Value = p.Required ? "Yes" : "No"; ws.Cell(r, 5).Value = p.Pattern;
            ws.Cell(r, 6).Value = p.ExpectedValue; ws.Cell(r, 7).Value = p.Notes;
            r++;
        }
        ws.Columns().AdjustToContents();

        var rd = wb.AddWorksheet("Readme");
        rd.Cell(1, 1).Value = "Purpose"; rd.Cell(1, 2).Value = "Generated by TestFlow from a sample CSV. Review every row: rules are guesses from the sample data.";
        rd.Cell(2, 1).Value = "Edit"; rd.Cell(2, 2).Value = "Change DataType / Required / Pattern / ExpectedValue where the sample was not representative.";
        rd.Columns().AdjustToContents();
        wb.SaveAs(path);
    }

    static void SaveCases(string path, string specPath, string csvPath, string delimiter)
    {
        var folder = Path.GetDirectoryName(Path.GetFullPath(csvPath)) ?? "";
        var file = Path.GetFileName(csvPath);
        using var wb = new XLWorkbook();
        var ws = wb.AddWorksheet("TestCases");
        string[] h = { "Id", "Name", "Description", "Type", "TimeoutSeconds", "FileCheckFolder", "FileNamePattern", "FileWaitSeconds", "SpecFile", "Delimiter", "HasHeader" };
        for (int i = 0; i < h.Length; i++) ws.Cell(1, i + 1).Value = h[i];
        ws.Row(1).Style.Font.Bold = true;

        void Row(int r, int id, string name, string desc, string pattern, string delim)
        {
            ws.Cell(r, 1).Value = id; ws.Cell(r, 2).Value = name; ws.Cell(r, 3).Value = desc; ws.Cell(r, 4).Value = "ExcelVerify";
            ws.Cell(r, 5).Value = 60; ws.Cell(r, 6).Value = folder; ws.Cell(r, 7).Value = pattern; ws.Cell(r, 8).Value = 0;
            ws.Cell(r, 9).Value = specPath; ws.Cell(r, 10).Value = delim; ws.Cell(r, 11).Value = "Yes";
        }
        // 1: the exact file, delimiter as given (blank = auto-detect)
        Row(2, 1, $"Verify CSV {file}", "Header, column types, required values, patterns and field count per line", file, delimiter);
        // 2: the newest CSV with the same extension in the folder (use after a job creates a new file)
        Row(3, 2, "Verify newest CSV in folder", "Same rules on the newest *.csv - chain it after a Run EXE node", "*" + Path.GetExtension(file), delimiter);
        // 3: delimiter forced to comma, catches files written with the wrong separator
        if (string.IsNullOrWhiteSpace(delimiter))
            Row(4, 3, "Verify CSV is comma separated", $"{file} must use a comma (a wrong delimiter shows up as Format / Missing column issues)", file, "comma");

        ws.Columns().AdjustToContents();
        wb.SaveAs(path);
    }
}
